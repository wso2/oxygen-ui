/**
 * Generates the StatusIllustration components from the SVGs in
 * packages/oxygen-ui/src/components/StatusIllustration/source.
 *
 * Only the light variants are used: the inverted files have the same shapes with dark-mode colour
 * defaults, and StatusIllustration sets those colours from the theme palette instead.
 *
 * Usage: node scripts/generate-status-illustrations.mjs
 */
import {readFileSync, writeFileSync, readdirSync, mkdirSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'oxygen-ui', 'src', 'components', 'StatusIllustration');
const srcDir = join(outDir, 'source');
const illustrationsDir = join(outDir, 'illustrations');
mkdirSync(illustrationsDir, {recursive: true});

const LICENSE = readFileSync(join(outDir, '..', 'ColorSchemeSVG', 'index.ts'), 'utf8').split('*/')[0] + '*/\n';
const HEADER = `${LICENSE}\n// Generated by scripts/generate-status-illustrations.mjs from ../source. Do not edit by hand.\n\n`;

const files = readdirSync(srcDir)
  .filter(f => f.endsWith('.svg') && !f.endsWith('-inverted.svg'))
  .sort((a, b) => a.localeCompare(b, 'en', {numeric: true}));

const cssRules = new Map();
const entries = [];

const pascal = s => s.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');

for (const file of files) {
  const base = file.replace(/\.svg$/, '');
  const svg = readFileSync(join(srcDir, file), 'utf8');

  // Collect the class rules; they are shared across the set and applied once by the wrapper.
  const style = svg.match(/<style>([\s\S]*?)<\/style>/)[1];
  for (const [, selector, body] of style.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const key = selector.trim();
    if (cssRules.has(key) && cssRules.get(key) !== body.trim()) {
      throw new Error(`Conflicting rule for ${key} in ${file}`);
    }
    cssRules.set(key, body.trim());
  }

  const label = svg.match(/aria-label="([^"]*)"/)[1];
  let body = svg
    .replace(/<style>[\s\S]*?<\/style>\s*/, '')
    .replace(/^\s*<svg[^>]*>\s*/, '')
    .replace(/\s*<\/svg>\s*$/, '');

  // Unique gradient ids per instance, so two copies on one page don't share defs.
  const ids = [...body.matchAll(/id="([^"]+)"/g)].map(m => m[1]);
  for (const id of ids) {
    const suffix = id.match(/^ho-([a-z])-/)[1];
    body = body
      .split(`id="${id}"`).join(`id={\`\${uid}-${suffix}\`}`)
      .split(`"url(#${id})"`).join(`{\`url(#\${uid}-${suffix})\`}`);
  }

  body = body
    .replace(/ class="/g, ' className="')
    .replace(/ style="stop-opacity:var\(--illustration-glow,([.\d]+)\)"/g, " style={{stopOpacity: 'var(--illustration-glow, $1)'}}")
    .replace(/ stop-color="#0A2AB4"/g, " style={{stopColor: 'var(--illustration-shade, #0A2AB4)'}}")
    .replace(/ stop-color="/g, ' stopColor="')
    .replace(/ stop-opacity="/g, ' stopOpacity="');

  if (/ [a-z]+-[a-z]+="/.test(body)) throw new Error(`Unconverted attribute in ${file}`);

  const key = base.replace(/^http-/, '').replace(/^state-/, '');
  const name = base.startsWith('http-') ? `Http${key}Illustration` : `${pascal(key)}Illustration`;
  const indented = body.split('\n').map(l => `      ${l.trim()}`).join('\n');

  writeFileSync(
    join(illustrationsDir, `${name}.tsx`),
    `${HEADER}import {JSX} from 'react';
import useIllustrationId from '../useIllustrationId';
import type {IllustrationSVGProps} from '../types';

export default function ${name}({width = 400, height = 300, ...rest}: IllustrationSVGProps): JSX.Element {
  const uid = useIllustrationId();

  return (
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300" width={width} height={height} role="img" aria-label="${label}" {...rest}>
${indented}
    </svg>
  );
}
`,
  );
  entries.push({key, name, label, isHttp: base.startsWith('http-')});
}

// Registry
writeFileSync(
  join(illustrationsDir, 'index.ts'),
  `${HEADER}import type {ComponentType} from 'react';
import type {IllustrationSVGProps} from '../types';
${entries.map(e => `import ${e.name} from './${e.name}';`).join('\n')}

/** HTTP status codes that have an illustration. */
export type StatusIllustrationHttpStatus = ${entries.filter(e => e.isHttp).map(e => e.key).join(' | ')};

/** Application states that have an illustration. */
export type StatusIllustrationState = ${entries.filter(e => !e.isHttp).map(e => `'${e.key}'`).join(' | ')};

export type StatusIllustrationStatus = StatusIllustrationHttpStatus | StatusIllustrationState;

/** Illustration component and default accessible label for each status. */
export const STATUS_ILLUSTRATIONS: Record<StatusIllustrationStatus, {component: ComponentType<IllustrationSVGProps>; label: string}> = {
${entries.map(e => `  ${e.isHttp ? e.key : `'${e.key}'`}: {component: ${e.name}, label: '${e.label}'},`).join('\n')}
};
`,
);

// Shared class styles, as an sx-compatible object
const toCamel = p => p.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

// The source files use the accent for both decoration and danger. These classes carry the danger
// meaning (the 5xx and failure core, and the error badges), so they get their own variable, which
// falls back to the accent.
const DANGER_CLASSES = ['ho-ce', 'ho-tp', 'ho-th', 'ho-ot', 'ho-ha', 'ho-ba'];
const isDanger = selector => selector.split(',').every(s => DANGER_CLASSES.includes(s.trim().slice(1)));

const styleLines = [...cssRules].map(([selector, decls]) => {
  const sel = selector.split(',').map(s => `& ${s.trim()}`).join(', ');
  if (isDanger(selector)) {
    decls = decls.replace(/var\(--illustration-accent,([^)]+)\)/g, 'var(--illustration-danger,var(--illustration-accent,$1))');
  }
  const props = decls
    .split(';')
    .filter(Boolean)
    .map(d => {
      const i = d.indexOf(':');
      return `${toCamel(d.slice(0, i).trim())}: '${d.slice(i + 1).trim()}'`;
    })
    .join(', ');
  return `  '${sel}': {${props}},`;
});

writeFileSync(
  join(outDir, 'illustrationStyles.ts'),
  `${HEADER}/**
 * Class styles shared by every status illustration. Colors come from the \`--illustration-*\`
 * CSS variables, which StatusIllustration maps to the theme palette.
 */
const illustrationStyles = {
${styleLines.join('\n')}
} as const;

export default illustrationStyles;
`,
);

console.log(`Generated ${entries.length} illustrations, ${cssRules.size} shared rules`);
