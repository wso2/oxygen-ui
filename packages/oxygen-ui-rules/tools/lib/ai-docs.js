import {existsSync, readdirSync, readFileSync} from 'fs';
import {join} from 'path';
import {REPO_ROOT, RULES_PACKAGE_DIR} from './repo.js';

/** Where `@wso2/oxygen-ui` keeps the AI assets that `npx @wso2/oxygen-ui init` installs. */
export const OXYGEN_UI_DIR = join(REPO_ROOT, 'packages/oxygen-ui');
export const CLAUDE_DIR = join(OXYGEN_UI_DIR, '.claude');
export const AI_DIR = join(OXYGEN_UI_DIR, '.ai');
export const SKILLS_DIR = join(CLAUDE_DIR, 'skills');

/** Guides written by hand in `.claude/`, and copied to `.ai/` by the generator. */
export const HAND_WRITTEN_GUIDES = ['patterns.md', 'theming.md', 'migration.md'];

/** Skills for maintainers of this repository, which are not listed for products. */
export const INTERNAL_SKILLS = ['oxygen-sync'];

export const SKILL_BLOCK_START = '<!-- oxygen-ui-rules:start -->';
export const SKILL_BLOCK_END = '<!-- oxygen-ui-rules:end -->';

const GENERATED_NOTE =
  '<!-- Generated by `pnpm rules:generate` from @wso2/oxygen-ui-rules and the @wso2/oxygen-ui type declarations. Do not edit: change the rules, the catalog or packages/oxygen-ui-rules/templates instead. -->';

const LEVEL_LABEL = {mandatory: 'Mandatory', recommended: 'Recommended', advisory: 'Advisory'};
const FIX_LABEL = {safe: 'automatic', suggestion: 'suggested', ai: 'AI assisted', manual: 'manual'};
const CATEGORY_LABEL = {
  imports: 'Imports',
  styling: 'Styling',
  components: 'Components',
  patterns: 'Patterns',
  accessibility: 'Accessibility',
  testability: 'Testability',
  content: 'Content',
};
const KIND_SECTIONS = [
  ['layout', 'Layout'],
  ['component', 'Components'],
  ['provider', 'Theming and providers'],
  ['hook', 'Hooks'],
  ['utility', 'Utilities'],
  ['animation', 'Animations'],
];

/**
 * Returns every generated AI asset with its content: the core instructions, the component API
 * reference and the rules, for Claude Code (`.claude/`) and other assistants (`.ai/`), the `.ai/`
 * copies of the hand-written guides, and the skills with their generated rule blocks.
 *
 * @param {typeof import('../../dist/index.js')} registry
 * @param {{all: Set<string>, owned: Map<string, object>}} api The `@wso2/oxygen-ui` API, from `readApiDetails`.
 * @returns {{path: string, content: string}[]}
 */
export function buildAiDocs(registry, api) {
  const skills = listSkills();
  const files = [
    {path: join(CLAUDE_DIR, 'CLAUDE.md'), content: buildCore(registry, {title: 'Claude Code Guide', docsPath: './', skills})},
    {path: join(AI_DIR, 'AGENTS.md'), content: buildCore(registry, {title: 'AI Development Guide', docsPath: '.ai/oxygen-ui/', skills: []})},
  ];

  for (const dir of [CLAUDE_DIR, AI_DIR]) {
    files.push({path: join(dir, 'components.md'), content: buildComponents(registry, api)});
    files.push({path: join(dir, 'rules.md'), content: buildRules(registry)});
  }

  for (const guide of HAND_WRITTEN_GUIDES) {
    files.push({path: join(AI_DIR, guide), content: readFileSync(join(CLAUDE_DIR, guide), 'utf-8')});
  }

  for (const skill of skills.filter((candidate) => candidate.hasBlock)) {
    files.push({path: skill.path, content: replaceSkillBlock(skill.content, buildSkillBlock(registry))});
  }

  return files;
}

/** The skills in `.claude/skills/`, with their front matter. */
function listSkills() {
  if (!existsSync(SKILLS_DIR)) {
    return [];
  }

  return readdirSync(SKILLS_DIR)
    .map((name) => ({name, path: join(SKILLS_DIR, name, 'SKILL.md')}))
    .filter(({path}) => existsSync(path))
    .map(({name, path}) => {
      const content = readFileSync(path, 'utf-8');
      const description = /^description:\s*(.+)$/m.exec(content)?.[1].trim() ?? '';

      return {name, path, content, description, hasBlock: content.includes(SKILL_BLOCK_START), internal: INTERNAL_SKILLS.includes(name)};
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function ruleLine({meta}) {
  return `- **${meta.title}** (\`${meta.id}\`, ${meta.level}): ${meta.summary}`;
}

function buildCore({rules, catalog, rulesetVersion}, {title, docsPath, skills}) {
  const template = readFileSync(join(RULES_PACKAGE_DIR, 'templates/core.md'), 'utf-8');
  const themes = catalog.components.find((entry) => entry.kind === 'theme');
  const themeNames = (themes?.exports ?? []).filter((name) => /^[A-Z]\w*Theme$/.test(name));
  const products = skills.filter((skill) => !skill.internal);

  const values = {
    title,
    docsPath,
    rulesetVersion,
    rules: rules.map(ruleLine).join('\n'),
    themes: [
      ...themeNames.map((name) => `- \`${name}\`${name === 'OxygenTheme' ? ' (default)' : ''}`),
      '',
      'Create a product theme from the Oxygen base with `createOxygenTheme`.',
    ].join('\n'),
    components: KIND_SECTIONS.map(([kind, label]) => {
      const entries = catalog.components.filter((entry) => entry.kind === kind);
      return entries.length === 0
        ? null
        : [`### ${label}`, '', ...entries.map((entry) => `- **${entry.name}** (${entry.exports.map((name) => `\`${name}\``).join(', ')}): ${entry.summary}`)].join('\n');
    })
      .filter(Boolean)
      .join('\n\n'),
    skills:
      products.length === 0
        ? ''
        : ['', '## Available skills', '', ...products.map((skill) => `- \`/${skill.name}\` - ${firstSentence(skill.description)}`)].join('\n'),
  };

  const content = template.replace(/\{\{(\w+)\}\}/g, (match, key) => (key in values ? values[key] : match));

  return `${GENERATED_NOTE}\n\n${content.trimEnd()}\n`;
}

function buildComponents({catalog}, api) {
  const lines = [
    GENERATED_NOTE,
    '',
    '# Oxygen UI component API',
    '',
    'Generated from the `@wso2/oxygen-ui` type declarations, so it matches the installed version. Import everything from `@wso2/oxygen-ui`. Oxygen UI also re-exports the MUI components; this reference lists what Oxygen UI adds.',
    '',
    'The tables list the props each component declares itself. Most components also accept the props of the MUI component they are built on. Storybook has examples of each component.',
  ];

  for (const [kind, label] of KIND_SECTIONS) {
    const entries = catalog.components.filter((entry) => entry.kind === kind);
    if (entries.length === 0) continue;

    lines.push('', `## ${label}`);

    for (const entry of entries) {
      lines.push('', `### ${entry.name}`, '', entry.summary, '');
      lines.push(`Exports: ${entry.exports.map((name) => `\`${name}\``).join(', ')}.${entry.story ? ` Storybook: ${entry.story}.` : ''}`);

      for (const name of entry.exports) {
        const value = api.owned.get(name);
        if (!value || (!value.props && !value.members)) continue;

        lines.push('', `#### ${name}`);
        if (value.description) lines.push('', value.description.replace(/\s+/g, ' '));
        if (value.props) lines.push('', ...propsTable(value.props));

        for (const [member, props] of Object.entries(value.members ?? {})) {
          lines.push('', `##### ${name}.${member}`, '', ...propsTable(props));
        }
      }
    }
  }

  const themes = catalog.components.find((entry) => entry.kind === 'theme');
  if (themes) {
    lines.push('', '## Themes', '', themes.summary, '', ...themes.exports.map((name) => `- \`${name}\``));
  }

  return `${lines.join('\n')}\n`;
}

function propsTable(props) {
  if (props.length === 0) {
    return ['No props of its own.'];
  }

  const cell = (text) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

  return [
    '| Prop | Type | Required | Description |',
    '|---|---|---|---|',
    ...props.map((prop) => `| \`${prop.name}\` | \`${cell(prop.type)}\` | ${prop.optional ? 'No' : 'Yes'} | ${cell(prop.description)} |`),
  ];
}

function buildRules({rules, rulesetVersion}) {
  const lines = [
    GENERATED_NOTE,
    '',
    '# Oxygen UI rules',
    '',
    `Rules version ${rulesetVersion}. The Oxygen UI analyzer and ESLint plugin check these rules.`,
    '',
    '- **Mandatory** rules must be followed, unless the product records an exception with a reason.',
    '- **Recommended** rules should be followed; deviations are reviewed.',
    '- **Advisory** rules are guidance.',
  ];

  for (const category of Object.keys(CATEGORY_LABEL)) {
    const inCategory = rules.filter((rule) => rule.meta.category === category);
    if (inCategory.length === 0) continue;

    lines.push('', `## ${CATEGORY_LABEL[category]}`);

    for (const {meta, docs, examples} of inCategory) {
      lines.push(
        '',
        `### ${meta.title}`,
        '',
        `\`${meta.id}\` · ${LEVEL_LABEL[meta.level]} · ${meta.enforcement === 'automated' ? 'Checked automatically' : 'Needs review'} · Fix: ${FIX_LABEL[meta.fix]}`,
        '',
        meta.summary,
        '',
        docs.trim().replace(/^## /gm, '#### '),
        '',
        '#### Examples',
      );

      for (const example of examples.valid) {
        lines.push('', `Correct: ${example.title}`, '', '```tsx', example.code, '```');
      }

      for (const example of examples.invalid) {
        lines.push('', `Incorrect: ${example.title}`, '', '```tsx', example.code, '```');

        if (example.output) {
          lines.push('', 'Fixed automatically to:', '', '```tsx', example.output, '```');
        }

        for (const suggestion of example.suggestions ?? []) {
          lines.push('', `Suggested fix (${suggestion.description}):`, '', '```tsx', suggestion.output, '```');
        }
      }
    }
  }

  return `${lines.join('\n')}\n`;
}

function buildSkillBlock({rules, rulesetVersion}) {
  return [
    SKILL_BLOCK_START,
    '<!-- Generated by `pnpm rules:generate`. Do not edit between these markers. -->',
    '',
    '## Oxygen UI rules',
    '',
    `Follow these rules (version ${rulesetVersion}) in all code you write or change. The Oxygen UI analyzer checks them. \`.claude/oxygen-ui/rules.md\` has how to fix each one, with examples.`,
    '',
    ...rules.map(ruleLine),
    SKILL_BLOCK_END,
  ].join('\n');
}

function replaceSkillBlock(content, block) {
  const start = content.indexOf(SKILL_BLOCK_START);
  const end = content.indexOf(SKILL_BLOCK_END);

  if (start === -1 || end === -1 || end < start) {
    return content;
  }

  return content.slice(0, start) + block + content.slice(end + SKILL_BLOCK_END.length);
}

function firstSentence(text) {
  const match = /^(.+?\.)(\s|$)/.exec(text);
  return (match ? match[1] : text).replace(/\.$/, '');
}

/**
 * Finds names that the hand-written AI docs import from `@wso2/oxygen-ui` but the package does not
 * export, such as removed or renamed components.
 *
 * @param {Set<string>} exported Every export name of `@wso2/oxygen-ui`.
 * @returns {{file: string, line: number, name: string}[]}
 */
export function findUnknownImports(exported) {
  const files = [
    ...HAND_WRITTEN_GUIDES.map((guide) => join(CLAUDE_DIR, guide)),
    ...listSkills().map((skill) => skill.path),
  ].filter((file) => existsSync(file));
  const unknown = [];

  for (const file of files) {
    const content = readFileSync(file, 'utf-8');
    const pattern = /import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*['"]@wso2\/oxygen-ui['"]/g;
    let match;

    while ((match = pattern.exec(content))) {
      const line = content.slice(0, match.index).split('\n').length;
      const names = match[1]
        .split(',')
        .map((specifier) => specifier.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0].trim())
        .filter(Boolean);

      for (const name of names) {
        if (!exported.has(name)) {
          unknown.push({file, line, name});
        }
      }
    }
  }

  return unknown;
}
