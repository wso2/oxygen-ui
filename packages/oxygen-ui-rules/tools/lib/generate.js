import {join} from 'path';
import {buildAiDocs} from './ai-docs.js';
import {readApiDetails} from './api.js';
import {REPO_ROOT, RULES_PACKAGE_DIR} from './repo.js';

/** The API snapshot, compared by `pnpm rules:coverage` to catch unreviewed API changes. */
export const API_SNAPSHOT_PATH = join(RULES_PACKAGE_DIR, 'src/catalog/api.snapshot.json');

/** The generated index of rules and catalog entries. */
export const RULES_INDEX_PATH = join(RULES_PACKAGE_DIR, 'RULES.md');

/** Packages whose API is snapshotted, by package name and directory. */
export const SNAPSHOT_PACKAGES = [{name: '@wso2/oxygen-ui', dir: join(REPO_ROOT, 'packages/oxygen-ui')}];

/**
 * Reads the API of every snapshotted package in detail: every export name, and the props and
 * sub-components of the values the package declares itself.
 *
 * @returns {Record<string, ReturnType<typeof readApiDetails>>}
 */
export function readApi() {
  return Object.fromEntries(SNAPSHOT_PACKAGES.map(({name, dir}) => [name, readApiDetails({packageDir: dir})]));
}

/**
 * The API snapshot: prop and sub-component names only, so it changes when the API does, not when
 * descriptions are edited.
 *
 * @param {ReturnType<typeof readApi>} api
 * @returns {Record<string, Record<string, {props?: string[], members?: Record<string, string[]>}>>}
 */
export function toSnapshot(api) {
  const names = (props) => props.map((prop) => `${prop.name}${prop.optional ? '?' : ''}`).sort();

  return Object.fromEntries(
    Object.entries(api).map(([pkg, {owned}]) => [
      pkg,
      Object.fromEntries(
        [...owned].map(([name, value]) => {
          const description = {};
          if (value.props) description.props = names(value.props);
          if (value.members) {
            description.members = Object.fromEntries(Object.entries(value.members).map(([member, props]) => [member, names(props)]));
          }
          return [name, description];
        }),
      ),
    ]),
  );
}

/**
 * Returns every generated file with the content it should have.
 *
 * @param {typeof import('../../dist/index.js')} registry
 * @param {ReturnType<typeof readApi>} api
 * @returns {{path: string, content: string}[]}
 */
export function buildGeneratedFiles(registry, api) {
  return [
    {path: API_SNAPSHOT_PATH, content: `${JSON.stringify(toSnapshot(api), null, 2)}\n`},
    {path: RULES_INDEX_PATH, content: buildRulesIndex(registry)},
    ...buildAiDocs(registry, api['@wso2/oxygen-ui']),
  ];
}

function buildRulesIndex({rules, catalog, rulesetVersion}) {
  const rulesFor = (type, key) =>
    rules
      .filter((rule) => rule.meta.sources.some((source) => source.type === type && (source.name ?? source.id) === key))
      .map((rule) => `\`${rule.meta.id}\``);
  const ruleList = (ids) => (ids.length > 0 ? ids.join(', ') : '_None yet_');
  const cell = (text) => text.replace(/\|/g, '\\|');

  const lines = [
    '<!-- Generated by `pnpm rules:generate` from the rule registry and catalog. Do not edit. -->',
    '',
    '# Oxygen UI rules',
    '',
    `Rule set version ${rulesetVersion}.`,
    '',
    '## Rules',
    '',
    '| Rule | Category | Level | Severity | Enforcement | Fix |',
    '|---|---|---|---|---|---|',
    ...rules.map(
      ({meta}) =>
        `| [\`${meta.id}\`](src/rules/${meta.id}/docs.md): ${cell(meta.title)} | ${meta.category} | ${meta.level} | ${meta.severity} | ${meta.enforcement} | ${meta.fix} |`,
    ),
    '',
    '## Components',
    '',
    '| Component | Kind | Exports | Rules |',
    '|---|---|---|---|',
    ...catalog.components.map(
      (entry) =>
        `| ${entry.name} | ${entry.kind} | ${entry.exports.map((name) => `\`${name}\``).join(', ')} | ${ruleList(rulesFor('component', entry.name))} |`,
    ),
    '',
    '## Packages',
    '',
    '| Package | Usage | Rules |',
    '|---|---|---|',
    ...catalog.packages.map(
      (entry) => `| \`${entry.name}\` | ${cell(entry.usage)} | ${ruleList(rulesFor('package', entry.name))} |`,
    ),
    '',
    '## Guides',
    '',
    '| Guide | Summary | Rules |',
    '|---|---|---|',
    ...catalog.guides.map((entry) => `| ${entry.id} | ${cell(entry.summary)} | ${ruleList(rulesFor('guide', entry.id))} |`),
    '',
  ];

  return lines.join('\n');
}
